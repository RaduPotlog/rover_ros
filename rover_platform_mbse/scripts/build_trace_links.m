function build_trace_links()
%BUILD_TRACE_LINKS Create the traceability links (Requirements Toolbox link sets).
%   Derive     SWR-<PFX>-NNN      -> SYS-SR-NNN     (from the SWR ParentSysSR attribute)
%   Implement  architecture component RoverPlatformArch/<Subsystem>/<package> -> its SWRs
%   Verify     test method in tests/t*.m -> the IDs on its "% Verifies:" line
%   Only links carrying the marker below are replaced, so links added by hand in the
%   Requirements Editor survive a re-run. The test link sets (tests/t*~m.slmx) hold
%   generated links only and are rebuilt, so edited test files never keep stale ranges.

% Copyright 2026 Mechatronics Academy
